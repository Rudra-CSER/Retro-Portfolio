export const GLYPH_H = 7;

export function glyph(ch) {
  return G[ch] || G[String(ch).toUpperCase()] || G['?'];
}

/**
 * Lays out lines of text into pixel coordinates.
 * Returns { pixels: [[x, y, line, char]], w, h, chars: [{line, char, x0, x1}] }
 */
export function layoutLines(lines, { letterGap = 1, lineGap = 3 } = {}) {
  const pixels = [];
  const chars = [];
  let maxW = 0;
  lines.forEach((line, li) => {
    let x = 0;
    const y0 = li * (GLYPH_H + lineGap);
    [...line].forEach((ch) => {
      const g = glyph(ch);
      const w = g[0].length;
      const ci = chars.length;
      if (ch !== ' ') chars.push({ line: li, x0: x, x1: x + w });
      for (let r = 0; r < GLYPH_H; r++) {
        for (let c = 0; c < w; c++) if (g[r][c] === '#') pixels.push([x + c, y0 + r, li, ch === ' ' ? -1 : ci]);
      }
      x += w + letterGap;
    });
    maxW = Math.max(maxW, x - letterGap);
  });
  const h = lines.length * GLYPH_H + (lines.length - 1) * lineGap;
  return { pixels, w: Math.max(1, maxW), h, chars };
}

export function measureText(str, letterGap = 1) {
  let w = 0;
  for (const ch of str) w += glyph(ch)[0].length + letterGap;
  return Math.max(0, w - letterGap);
}

/** Draws text onto a 2D canvas with square pixels of size `scale` (crisp, no AA). */
export function drawPixelText(ctx, str, x, y, { scale = 1, color = '#fff', align = 'left', shadow = null, tall = 1 } = {}) {
  const text = String(str).toUpperCase();
  const w = measureText(text) * scale;
  let cx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const cy = Math.round(y);
  const ph = Math.round(scale * tall);
  const pass = (dx, dy, col) => {
    ctx.fillStyle = col;
    let px = cx + dx;
    for (const ch of text) {
      const g = glyph(ch);
      const gw = g[0].length;
      for (let r = 0; r < GLYPH_H; r++) {
        const row = g[r];
        for (let c = 0; c < gw; c++) if (row[c] === '#') ctx.fillRect(px + c * scale, cy + dy + r * ph, scale, ph);
      }
      px += (gw + 1) * scale;
    }
  };
  if (shadow) pass(scale, scale, shadow);
  pass(0, 0, color);
  return w;
}
